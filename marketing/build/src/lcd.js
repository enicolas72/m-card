export const COLS = 20;
export const ROWS = 4;
const SCROLL_GAP = '   ';
const STATE_ICONS = { playing: '>', paused: '||', stopped: '[]', loading: '..' };

export function toLcdAscii(text) {
  return text.normalize('NFKD').replace(/[̀-ͯ]/g, '')
    .replace(/[’‘]/g, "'").replace(/[–—]/g, '-').replace(/[^\x20-\x7e]/g, '');
}

export function nowPlayingLines(state, album, track, artist) {
  return [`${STATE_ICONS[state] || '?'} ${state}`, album, track, artist];
}

// Screen: logical lines (possibly > 20 chars) + scrolling.
export class Lcd {
  constructor(canvas, { scale = 4, backlight = true } = {}) {
    this.canvas = canvas;
    this.ctx = canvas.getContext('2d');
    this.scale = scale;           // dot size in canvas px
    this.gap = Math.max(1, Math.round(scale * 0.18));
    this.lines = ['', '', '', ''];
    this.offsets = [0, 0, 0, 0];
    this.backlight = backlight;
    const pitch = scale;
    this.cellW = 5 * pitch; this.cellH = 8 * pitch;
    this.charGap = pitch; this.lineGap = pitch;
    this.pad = pitch * 3;
    canvas.width = this.pad * 2 + COLS * this.cellW + (COLS - 1) * this.charGap;
    canvas.height = this.pad * 2 + ROWS * this.cellH + (ROWS - 1) * this.lineGap;
    this.onDraw = null;
    this.draw();
  }

  setLines(lines) {
    lines.forEach((l, i) => {
      const t = toLcdAscii(l || '');
      if (t !== this.lines[i]) { this.lines[i] = t; this.offsets[i] = 0; }
    });
    this.draw();
  }

  tick() {  // called every 0.6 s (SCROLL_PERIOD_S)
    let changed = false;
    this.lines.forEach((l, i) => { if (l.length > COLS) { this.offsets[i]++; changed = true; } });
    if (changed) this.draw();
  }

  visible(row) {
    const text = this.lines[row];
    if (text.length <= COLS) return text.padEnd(COLS);
    const loop = text + SCROLL_GAP;
    const off = this.offsets[row] % loop.length;
    return (loop + loop).slice(off, off + COLS);
  }

  draw() {
    const { ctx, canvas, scale: p } = this;
    const on = this.backlight;
    const g = ctx.createLinearGradient(0, 0, 0, canvas.height);
    g.addColorStop(0, on ? '#2c4dff' : '#0b1030');
    g.addColorStop(1, on ? '#1630d8' : '#070a20');
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    const dotOff = on ? 'rgba(120,150,255,0.16)' : 'rgba(80,100,200,0.06)';
    const dotOn = on ? '#eef3ff' : '#3b4a8a';
    const r = p - this.gap;
    for (let row = 0; row < ROWS; row++) {
      const text = this.visible(row);
      for (let col = 0; col < COLS; col++) {
        const code = text.charCodeAt(col);
        const idx = (code >= 0x20 && code <= 0x7e ? code - 0x20 : 0) * 5;
        const x0 = this.pad + col * (this.cellW + this.charGap);
        const y0 = this.pad + row * (this.cellH + this.lineGap);
        for (let cx = 0; cx < 5; cx++) {
          const bits = FONT[idx + cx];
          for (let cy = 0; cy < 8; cy++) {
            const lit = cy < 7 && (bits >> cy) & 1;
            ctx.fillStyle = lit ? dotOn : dotOff;
            ctx.fillRect(x0 + cx * p, y0 + cy * p, r, r);
          }
        }
      }
    }
    if (this.onDraw) this.onDraw();
  }
}
